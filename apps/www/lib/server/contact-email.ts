import { Resend } from "resend";

export interface ContactLead {
  name: string;
  school: string;
  email: string;
  phone: string;
  students: string;
  message: string;
  campaign: string;
  timestamp: string;
}

const DEFAULT_FROM = "Melo <hey@jstarstudios.com>";
const DEFAULT_TO = "melo@jstarstudios.com";

function escapeHtml(value: string) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

